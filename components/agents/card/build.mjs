#!/usr/bin/env node
// Builds the MCP Apps task card (apps/card.html) as one self-contained HTML document and writes it to
// supabase/functions/_shared/cardHtml.ts, which the mcp function serves as ui://colabora/task-card.html.
// The module is committed, so a deploy needs no build. Run `npm run build:card` after changing the card
// or the panel views, and commit the result.
//
// It runs its own Vite build (same plugins as vite.config.ts, only the card entry, one JS and one CSS
// chunk) into dist/card-inline/, then inlines the script and the stylesheet into the page.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const outDir = path.join(root, "dist", "card-inline");
const target = path.join(root, "supabase", "functions", "_shared", "cardHtml.ts");
const LIMIT = 300 * 1024;

await build({
  configFile: false,
  root,
  logLevel: "warn",
  plugins: [react(), tailwindcss()],
  resolve: { alias: { "@": root, "next/navigation": path.join(root, "lib", "routerCompat.ts") } },
  define: {
    "process.env.NEXT_PUBLIC_MCP_URL": JSON.stringify(""),
    "process.env.NEXT_PUBLIC_SUPABASE_URL": JSON.stringify(""),
  },
  build: {
    outDir,
    emptyOutDir: true,
    modulePreload: false,
    cssCodeSplit: false,
    assetsInlineLimit: Number.MAX_SAFE_INTEGER,
    sourcemap: false,
    reportCompressedSize: false,
    rollupOptions: {
      input: path.join(root, "apps", "card.html"),
      output: { inlineDynamicImports: true },
    },
  },
});

const page = await readFile(path.join(outDir, "apps", "card.html"), "utf8");
const asset = (src) => readFile(path.join(outDir, src.replace(/^\//, "")), "utf8");
let html = page;

for (const match of page.matchAll(/<script type="module"[^>]*\ssrc="([^"]+)"[^>]*><\/script>/g)) {
  const js = await asset(match[1]);
  // The script must not close itself: "</script" inside a string literal becomes "<\/script".
  if (/<!--/.test(js) && /<script/i.test(js)) {
    throw new Error("card build: the bundle contains '<!--' and '<script', which the HTML parser would misread inside an inline script");
  }
  const inlined = `<script type="module">${js.replace(/<\/script/gi, "<\\/script")}</script>`;
  html = html.replace(match[0], () => inlined);
}
for (const match of page.matchAll(/<link rel="stylesheet"[^>]*\shref="([^"]+)"[^>]*>/g)) {
  const css = await asset(match[1]);
  const inlined = `<style>${css.replace(/<\/style/gi, "<\\/style")}</style>`;
  html = html.replace(match[0], () => inlined);
}
if (/\s(?:src|href)="\/assets\//.test(html)) throw new Error("card build: an asset reference was not inlined");
if (/<link rel="modulepreload"/.test(html)) throw new Error("card build: a modulepreload link was left in the page");

const bytes = Buffer.byteLength(html, "utf8");
if (bytes > LIMIT) console.warn(`card build: ${bytes} bytes is over the ${LIMIT} byte target; import less into the card`);

const banner = [
  `// Generated by components/agents/card/build.mjs from apps/card.html (${bytes} bytes). Do not edit by hand.`,
  "// The MCP Apps task card as one self-contained HTML document (inline script and styles, no network),",
  "// served by the mcp function as the ui://colabora/task-card.html resource.",
].join("\n");
await writeFile(target, `${banner}\nexport const CARD_HTML: string = ${JSON.stringify(html)};\n`, "utf8");
console.log(`card: ${bytes} bytes -> ${path.relative(root, target)}`);
