export function searchEmoji(query: string, limit = 12): EmojiEntry[] {
  const q = query.toLowerCase();
  if (!q) return EMOJI_LIST.slice(0, limit);
  const starts: EmojiEntry[] = [];
  const includes: EmojiEntry[] = [];
  for (const e of EMOJI_LIST) {
    if (e.name === q) starts.unshift(e);          // coincidencia exacta: primera
    else if (e.name.startsWith(q)) starts.push(e);
    else if (e.name.includes(q)) includes.push(e);
    if (starts.length >= limit) break;            // corta en cuanto hay `limit` prefijos
  }
  return [...starts, ...includes].slice(0, limit);
}
